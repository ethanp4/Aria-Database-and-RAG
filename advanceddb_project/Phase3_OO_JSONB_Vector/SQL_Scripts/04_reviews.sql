-- Aria Phase 3 / 04: product reviews, the searchable text (2,390 clean rows).
-- Run with psql from this folder: \copy reads ../Embeddings/data/reviews_clean.csv on the CLIENT.
-- (pgAdmin users: open "PSQL Tool" in this folder, or use Import/Export on the CSV.)
--
-- Phase 2 kept reviews in Firestore (prototype). In Phase 3 they move into PostgreSQL so they can
-- be joined to products, the hierarchy, and their embeddings. Keys:
--   product_id -> products(product_id)   BIGINT, composition: deleting a product deletes its reviews
--   account_id -> accounts(account_id)   BIGINT, the reviewer (a customer)
--   order_id   -> orders(order_id)       BIGINT, NULL unless it is a verified purchase
--
-- Relational vs JSONB vs embedded:
--   relational  rating, title, helpful_votes, created_at, the keys       (fixed, always present, filtered/aggregated)
--   JSONB       details: sub-ratings (fit only for wearables), optional dive_context {site, region,
--               water_temp_c, depth_m}, optional photos[]               (varies per review)
--   embedded    title + '. ' + body -> review_embeddings (05_vectors.sql)
--   full-text   body_tsv, generated from the same text (hybrid search, C3)

CREATE TABLE product_reviews (
    review_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT       NOT NULL,
    account_id      BIGINT       NOT NULL,
    order_id        BIGINT,
    rating          SMALLINT     NOT NULL,
    title           VARCHAR(120) NOT NULL,
    body            TEXT         NOT NULL,
    details         JSONB        NOT NULL DEFAULT '{}',
    helpful_votes   INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    body_tsv        TSVECTOR GENERATED ALWAYS AS (to_tsvector('english', title || ' ' || body)) STORED,
    CONSTRAINT reviews_rating_valid   CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT reviews_body_not_blank CHECK (btrim(body) <> ''),
    CONSTRAINT reviews_votes_valid    CHECK (helpful_votes >= 0),
    -- one review per customer per product (also blocks double-submitted duplicates)
    CONSTRAINT reviews_one_per_customer_product UNIQUE (account_id, product_id),
    -- JSON shape: an object; dive_context / ratings are objects; water temperature is a number
    CONSTRAINT reviews_details_valid CHECK (
        jsonb_typeof(details) = 'object'
        AND jsonb_typeof(COALESCE(details -> 'ratings', '{}')) = 'object'
        AND jsonb_typeof(COALESCE(details -> 'dive_context', '{}')) = 'object'
        AND jsonb_typeof(COALESCE(details #> '{dive_context,water_temp_c}', '0')) = 'number'
        AND jsonb_typeof(COALESCE(details -> 'photos', '[]')) = 'array'),
    CONSTRAINT reviews_product_fk FOREIGN KEY (product_id) REFERENCES products (product_id) ON DELETE CASCADE,
    CONSTRAINT reviews_account_fk FOREIGN KEY (account_id) REFERENCES accounts (account_id) ON DELETE CASCADE,
    CONSTRAINT reviews_order_fk   FOREIGN KEY (order_id)   REFERENCES orders (order_id)   ON DELETE SET NULL
);

CREATE INDEX reviews_product_idx  ON product_reviews (product_id);       -- FK + "reviews of product X"
CREATE INDEX reviews_order_idx    ON product_reviews (order_id) WHERE order_id IS NOT NULL;
CREATE INDEX reviews_tsv_gin      ON product_reviews USING gin (body_tsv);
CREATE INDEX reviews_details_gin  ON product_reviews USING gin (details jsonb_path_ops);
-- account_id is covered by the leading column of reviews_one_per_customer_product

-- R5: a review can only claim a verified purchase for an order that belongs to the reviewer,
-- contains the product, and was delivered.
CREATE FUNCTION fn_check_verified_purchase() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.order_id IS NOT NULL AND NOT EXISTS (
        SELECT 1
        FROM orders o
        JOIN order_items oi ON oi.order_id = o.order_id
        WHERE o.order_id = NEW.order_id
          AND o.account_id = NEW.account_id
          AND oi.product_id = NEW.product_id
          AND o.delivered_at IS NOT NULL)
    THEN
        RAISE EXCEPTION 'Review cannot be verified: order % was not delivered to account % with product %',
                        NEW.order_id, NEW.account_id, NEW.product_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_reviews_verified_purchase
    BEFORE INSERT OR UPDATE OF order_id, account_id, product_id ON product_reviews
    FOR EACH ROW EXECUTE FUNCTION fn_check_verified_purchase();

\copy product_reviews (review_id, product_id, account_id, order_id, rating, title, body, details, helpful_votes, created_at) FROM '../Embeddings/data/reviews_clean.csv' WITH (FORMAT csv, HEADER true)

SELECT setval(pg_get_serial_sequence('product_reviews', 'review_id'), (SELECT max(review_id) FROM product_reviews));
-- VACUUM flushes the GIN pending list and sets the visibility map, so plans match a settled table
VACUUM ANALYZE product_reviews;

SELECT count(*) AS reviews,
       count(order_id) AS verified,
       count(DISTINCT product_id) AS products,
       count(DISTINCT account_id) AS reviewers
FROM product_reviews;
