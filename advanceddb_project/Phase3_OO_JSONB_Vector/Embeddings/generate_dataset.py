"""Aria Phase 3: deterministic synthetic data for the product hierarchy, JSONB specs and reviews.

Step 1 of the pipeline (see run_pipeline.py). Standard library only.

Inputs
    ../../Phase2_Implementation/SQL_Scripts/generate_seed.py
        The Phase 2 simulation (seed 2026). We re-run it in memory so every product, customer
        and order referenced here exists in aria_phase2 with the same id.

Outputs (all regenerated byte-for-byte identically on every run)
    ../SQL_Scripts/02_product_seed.sql   product_kind + specs JSONB for all 200 products and one
                                         row per product in its subclass table
    data/reviews_raw.csv                 ~2,440 raw product reviews, *with* the data-quality
                                         problems a real export has (duplicates, empty and very
                                         short bodies, stray whitespace, HTML entities, very long
                                         bodies). clean_reviews.py fixes them.
    eval/ground_truth.csv                hidden topic labels per review (never loaded into the
                                         database); evaluate.py uses them to mark search results
                                         relevant / not relevant.

How the text is made
    Every review is assembled from hand-written sentence banks (written with Claude Code for this
    project). Each product type has a set of topics (fogging, warmth, battery life, ...). Each topic
    has several *paraphrases* for a positive and a negative experience, many of which avoid the
    obvious keyword ("the lens kept misting over" instead of "fogging"), so that meaning-based search
    has something to do that keyword search cannot. All data is synthetic.

Usage
    python generate_dataset.py            # write the three outputs
    python generate_dataset.py --check    # exit 1 if any committed output is out of date
"""
