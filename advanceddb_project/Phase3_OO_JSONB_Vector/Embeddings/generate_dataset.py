def sql_literal(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'TRUE' if v else 'FALSE'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


SUBCLASS_COLUMNS = {
    'WEARABLE': ('wearable_gear', ('material', 'thickness_mm', 'fit_type')),
    'LIFE_SUPPORT': ('life_support_equipment', ('service_interval_months', 'max_depth_m', 'cold_water_rated')),
    'ELECTRONICS': ('dive_electronics', ('battery_type', 'battery_life_h', 'warranty_months')),
    'ACCESSORY': ('safety_accessory', ('visibility_rating', 'corrosion_resistant')),
}


def render_product_sql(tables, kinds, rows, specs):
    out = ['-- Aria Phase 3: product hierarchy + JSONB specs seed. GENERATED by',
           '-- Embeddings/generate_dataset.py; do not edit by hand. Synthetic data only.',
           '-- Run after 01_hierarchy_tables.sql, while connected to aria_phase2.',
           '--', '-- Rows:']
    counts = {}
    for pid in sorted(kinds):
        counts[kinds[pid][0]] = counts.get(kinds[pid][0], 0) + 1
    out += [f'--   {SUBCLASS_COLUMNS[k][0]:<24} {counts[k]:>4}' for k in SUBCLASS_COLUMNS]
    out += ['', 'BEGIN;', '', '-- superclass: discriminator + semi-structured attributes',
            'UPDATE products AS p', '   SET product_kind = v.kind, specs = v.specs::jsonb', '  FROM (VALUES']
    vals = [f"    ({pid}, '{kinds[pid][0]}', {sql_literal(json.dumps(specs[pid]))})" for pid in sorted(kinds)]
    out.append(',\n'.join(vals))
    out += [') AS v(product_id, kind, specs)', ' WHERE p.product_id = v.product_id;', '']
    for kind, (table, cols) in SUBCLASS_COLUMNS.items():
        out.append(f'-- subclass {table}')
        out.append(f'INSERT INTO {table} (product_id, {", ".join(cols)}) VALUES')
        lines = [f'    ({pid}, ' + ', '.join(sql_literal(rows[pid][c]) for c in cols) + ')'
                 for pid in sorted(kinds) if kinds[pid][0] == kind]
        out.append(',\n'.join(lines) + ';')
        out.append('')
    out += ['COMMIT;', '']
    return '\n'.join(out)


def render_csv(header, records):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator='\n')
    w.writerow(header)
    w.writerows(records)
    return buf.getvalue()


def generate():
    tables = load_phase2_tables()
    rng = random.Random(SEED)
    kinds, rows, specs = {}, {}, {}
    typed = [(p, product_type(p['sku'])) for p in tables['products']]
    skus_by_type = {}
    for p, t in typed:
        skus_by_type.setdefault(t, []).append(p['sku'])
    for p, t in typed:
        variant = product_variant(p)
        kinds[p['product_id']] = (TYPE_KIND[t], t)
        rows[p['product_id']] = subclass_row(p, t, variant, rng)
        specs[p['product_id']] = specs_for(p, t, variant, rng, skus_by_type)
    reviews = build_reviews(tables, kinds)

    sql = render_product_sql(tables, kinds, rows, specs)
    raw = render_csv(
        ['review_id', 'product_id', 'account_id', 'order_id', 'rating', 'title', 'body', 'details',
         'helpful_votes', 'created_at'],
        [[r['review_id'], r['product_id'], r['account_id'], r['order_id'] or '', r['rating'], r['title'],
          r['body'], json.dumps(r['details'], separators=(',', ':')), r['helpful_votes'],
          r['created_at'].strftime('%Y-%m-%d %H:%M:%S+00')] for r in reviews])
    truth = render_csv(
        ['review_id', 'product_type', 'topics'],
        [[r['review_id'], kinds[r['product_id']][1], '|'.join(f'{t}:{p}' for t, p in r['topics'])]
         for r in reviews])
    return {OUT_SQL: sql, OUT_RAW: raw, OUT_TRUTH: truth}


def main():
    parser = argparse.ArgumentParser(description='Generate Phase 3 synthetic product specs and reviews.')
    parser.add_argument('--check', action='store_true', help='fail if a committed output is out of date')
    args = parser.parse_args()
    outputs = generate()
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
            print(f'wrote {path.relative_to(PHASE3)} ({len(text):,} bytes)')
    if args.check:
        if stale:
            print('out of date: ' + ', '.join(str(p.relative_to(PHASE3)) for p in stale))
            sys.exit(1)
        print('all generated files are up to date')


if __name__ == '__main__':
    main()
