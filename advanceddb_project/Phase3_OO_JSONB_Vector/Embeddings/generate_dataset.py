def product_type(sku):
    if sku in NAMED_TYPES:
        return NAMED_TYPES[sku]
    return FAMILY_TYPES[sku.split('-')[1]]          # GEN-<FAMILY>-<nn>


def product_variant(p):
    """'Cold-water', 'Travel', ... for generated variants; None for the 30 named products."""
    return p['name'].split(' ')[0] if p['sku'].startswith('GEN-') else None


def neoprene_mm(variant, default):
    return {'Cold-water': 7.0, 'Expedition': 7.0, 'Warm-water': 3.0, 'Lightweight': 2.0,
            'Travel': 3.0}.get(variant, default)


def subclass_row(p, ptype, variant, rng):
    """Relational subclass attributes: fixed, always present for the subclass, so they are columns."""
    kind = TYPE_KIND[ptype]
    pro = variant in ('Professional', 'Technical', 'Expedition')
    if kind == 'WEARABLE':
        if ptype == 'mask':
            return {'material': 'tempered glass, silicone', 'thickness_mm': None, 'fit_type': 'FACE_SEAL'}
        if ptype == 'snorkel':
            return {'material': 'silicone', 'thickness_mm': None, 'fit_type': 'MOUTHPIECE'}
        if ptype == 'fins':
            full_foot = p['sku'] == 'FIN-003' or variant == 'Warm-water'
            return {'material': 'polypropylene, thermo-rubber', 'thickness_mm': None,
                    'fit_type': 'FULL_FOOT' if full_foot else 'OPEN_HEEL'}
        base = {'SUIT-001': 3.0, 'SUIT-002': 5.0}.get(p['sku'], 5.0 if ptype != 'gloves' else 3.0)
        fit = {'wetsuit': 'FULL_BODY', 'hood': 'HOOD', 'gloves': 'HAND', 'boots': 'BOOT'}[ptype]
        return {'material': 'neoprene', 'thickness_mm': neoprene_mm(variant, base), 'fit_type': fit}
    if kind == 'LIFE_SUPPORT':
        cold = variant in ('Cold-water', 'Technical', 'Professional') or p['sku'] in ('REG-001', 'GAUGE-001')
        depth = {'gauge': 100, 'hose': 100}.get(ptype, 100 if variant == 'Technical' else 40 if not pro else 60)
        return {'service_interval_months': 24 if (pro or ptype in ('gauge', 'hose')) else 12,
                'max_depth_m': depth, 'cold_water_rated': cold}
    if kind == 'ELECTRONICS':
        if ptype == 'light':
            return {'battery_type': 'RECHARGEABLE_LI_ION', 'battery_life_h': rng.choice([2, 3, 4, 6, 8]),
                    'warranty_months': 24 if pro else 12}
        replaceable = ptype == 'console_computer' or variant in ('Compact', 'Recreational')
        warranty = 36 if pro else 12 if variant in ('Compact', 'Lightweight') else 24
        hours = rng.choice([150, 200, 300]) if replaceable else rng.choice([30, 40, 50, 60, 80])
        return {'battery_type': 'USER_REPLACEABLE' if replaceable else 'RECHARGEABLE_LI_ION',
                'battery_life_h': hours, 'warranty_months': warranty}
    visibility = {'smb': 5, 'whistle': 4, 'compass': 2, 'depth_gauge': 2, 'reel': 2, 'cutter': 1}[ptype]
    return {'visibility_rating': visibility, 'corrosion_resistant': ptype != 'compass' or variant == 'Professional'}


def sizes(ptype, rng):
    """Array of objects: the size run differs per product type, and some sizes are unavailable."""
    def avail():
        return rng.random() > 0.12
    if ptype == 'wetsuit':
        return [{'size': s, 'chest_cm': c, 'height_cm': h, 'available': avail()}
                for s, c, h in (('XS', 84, 160), ('S', 90, 167), ('M', 96, 174), ('L', 102, 180),
                                ('XL', 108, 186), ('XXL', 114, 190))]
    if ptype == 'bcd':
        return [{'size': s, 'chest_cm': c, 'available': avail()} for s, c in
                (('S', 88), ('M', 98), ('L', 108), ('XL', 118))]
    if ptype in ('fins', 'boots'):
        return [{'size': s, 'foot_eu': f, 'available': avail()} for s, f in
                (('36-37', 36.5), ('38-39', 38.5), ('40-41', 40.5), ('42-43', 42.5), ('44-45', 44.5))]
    return [{'size': s, 'available': avail()} for s in ('S', 'M', 'L', 'XL')]   # hood, gloves


def specs_for(p, ptype, variant, rng, skus_by_type):
    """Semi-structured attributes: which keys exist depends on the product, so they live in JSONB."""
    weight = {'mask': 180, 'snorkel': 90, 'wetsuit': 2400, 'hood': 300, 'gloves': 220, 'fins': 1300,
              'boots': 700, 'reg_first': 620, 'reg_second': 190, 'gauge': 300, 'hose': 140, 'bcd': 3100,
              'computer': 120, 'ai_computer': 160, 'console_computer': 680, 'light': 420, 'compass': 90,
              'depth_gauge': 110, 'smb': 380, 'reel': 260, 'cutter': 70, 'whistle': 20}[ptype]
    if variant in ('Travel', 'Lightweight', 'Compact'):
        weight = int(weight * 0.7)
    spec = {'weight_g': int(weight * rng.uniform(0.92, 1.08)),
            'colours': sorted(rng.sample(COLOURS, rng.randint(1, 3)))}
    nitrox = not (ptype == 'console_computer' or variant == 'Compact')
    tech = variant == 'Technical'
    if ptype in ('wetsuit', 'hood', 'gloves', 'fins', 'boots', 'bcd'):
        spec['sizes'] = sizes(ptype, rng)
    features = {}
    if ptype == 'mask':
        features = {'lens': 'frameless' if p['sku'] == 'MASK-003' else rng.choice(['single', 'dual']),
                    'prescription_ready': p['sku'] == 'MASK-004' or rng.random() < 0.3,
                    'skirt': rng.choice(['clear silicone', 'black silicone']), 'volume_ml': rng.randint(95, 190)}
    elif ptype == 'snorkel':
        features = {'valve': rng.choice(['purge', 'dry-top', 'semi-dry']), 'foldable': variant == 'Travel'}
    elif ptype == 'wetsuit':
        features = {'zip': rng.choice(['back', 'chest']), 'knee_pads': rng.random() < 0.6,
                    'seals': sorted(rng.sample(['wrist', 'ankle', 'neck'], 2))}
    elif ptype == 'fins':
        features = {'blade': 'split' if p['sku'] == 'FIN-002' else rng.choice(['paddle', 'paddle', 'vented']),
                    'strap': rng.choice(['spring', 'rubber', 'bungee'])}
    elif ptype in ('reg_first', 'reg_second'):
        features = {'nitrox_compatible': nitrox, 'max_o2_pct': 100 if tech else 40}
        if ptype == 'reg_first':
            features.update({'design': rng.choice(['balanced diaphragm', 'balanced piston']),
                             'environmentally_sealed': variant in ('Cold-water', 'Technical') or p['sku'] == 'REG-001',
                             'ports': {'lp': 4 if not tech else 5, 'hp': 2}})
        else:
            features.update({'adjustable_resistance': True, 'venturi_switch': rng.random() < 0.7})
        spec['certifications'] = ['CE', 'EN250']
    elif ptype == 'bcd':
        features = {'style': 'back-inflate', 'lift_kg': 13 if variant == 'Travel' else rng.choice([16, 18, 20]),
                    'integrated_weights': True, 'pockets': rng.randint(2, 4)}
        spec['certifications'] = ['EN1809']
    elif ptype in ('computer', 'ai_computer', 'console_computer'):
        features = {'nitrox': nitrox, 'max_o2_pct': (100 if tech else 40) if nitrox else 21,
                    'gas_mixes': 3 if tech else (2 if nitrox else 1), 'air_integrated': ptype == 'ai_computer',
                    'algorithm': 'Buhlmann ZHL-16C' if rng.random() < 0.6 else 'RGBM',
                    'modes': ['air', 'nitrox', 'gauge'] if nitrox else ['air', 'gauge']}
        if rng.random() < 0.4:
            features['modes'].append('freedive')
        spec['certifications'] = ['EN13319']
    elif ptype == 'light':
        features = {'lumens': rng.choice([800, 1200, 2000, 3000]), 'beam_angle_deg': rng.choice([8, 12, 70, 100])}
    elif ptype == 'compass':
        features = {'luminous': True, 'bezel': 'rotating'}
    elif ptype == 'depth_gauge':
        features = {'max_reading_m': 80}
    elif ptype == 'smb':
        features = {'height_cm': rng.choice([100, 140, 180]), 'closed': rng.random() < 0.7,
                    'inflation': rng.choice(['oral', 'oral + LP'])}
    elif ptype == 'reel':
        features = {'line_m': 30 if p['sku'] == 'REEL-001' else rng.choice([30, 45, 60]), 'line_type': 'braided nylon'}
    elif ptype == 'cutter':
        features = {'blade': rng.choice(['stainless 316', 'titanium']), 'mount': rng.choice(['BCD hose', 'webbing'])}
    elif ptype == 'whistle':
        features = {'db': rng.choice([110, 115, 120])}
    if features:
        spec['features'] = features

    # compatibility list: array of objects that point at other products by SKU
    compat = []
    if ptype == 'reg_first':
        compat = [{'sku': s, 'note': 'second stage on LP port'} for s in sorted(rng.sample(skus_by_type['reg_second'], 2))]
        compat.append({'sku': 'HOSE-001', 'note': 'standard 3/8 in. LP hose'})
    elif ptype == 'reg_second':
        compat = [{'sku': s, 'note': 'fits this first stage'} for s in sorted(rng.sample(skus_by_type['reg_first'], 2))]
    elif ptype == 'ai_computer':
        compat = [{'sku': s, 'note': 'HP port for the wireless transmitter'}
                  for s in sorted(rng.sample(skus_by_type['reg_first'], 2))]
    elif ptype == 'bcd':
        compat = [{'sku': 'REG-003', 'note': 'alternate air source on the inflator hose'}]
    elif ptype == 'smb':
        compat = [{'sku': rng.choice(skus_by_type['reel']), 'note': 'matching reel'}]
    if compat:
        spec['compatible_with'] = compat
    return spec


