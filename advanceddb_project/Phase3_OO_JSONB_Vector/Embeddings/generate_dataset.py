def pick_site(rng, topics):
    names = {t for t, _ in topics}
    if names & COLD_TOPICS or any(t == 'battery' and pol == 'neg' for t, pol in topics) and rng.random() < 0.5:
        pool = COLD_SITES
    else:
        pool = rng.choice([COLD_SITES, WARM_SITES, WARM_SITES, MILD_SITES])
    name, region, (lo, hi) = rng.choice(pool)
    return name, region, rng.randint(lo, hi)


def polarity_for(rating, rng):
    p_pos = {5: 0.95, 4: 0.8, 3: 0.5, 2: 0.2, 1: 0.07}[rating]
    return 'pos' if rng.random() < p_pos else 'neg'


def build_review_text(rng, product, ptype, rating, long_form=False):
    """Returns (title, body, topics[(topic, polarity)], site_or_None)."""
    specific = [t for t, (types, _, _) in TOPICS.items() if ptype in types and t not in GENERIC_TOPICS]
    n_specific = len(specific) if long_form else min(len(specific), rng.choice([1, 1, 2, 2, 3]))
    chosen = rng.sample(specific, n_specific)
    if long_form or rng.random() < 0.35:
        chosen.append(rng.choice(GENERIC_TOPICS))
    topics = [(t, polarity_for(rating, rng)) for t in chosen]
    site = pick_site(rng, topics)
    name = product['name'].lower()
    sentences = [rng.choice(OPENERS[rating]).format(name=name, dives=rng.randint(2, 60), site=site[0])]
    for t, pol in topics:
        pos, neg = TOPICS[t][1], TOPICS[t][2]
        bank = pos if pol == 'pos' else neg
        if long_form:
            sentences.extend(rng.sample(bank, min(len(bank), 2)))
        else:
            sentences.append(rng.choice(bank))
    if long_form:
        story = rng.sample(STORY, 10)
        for i, s in enumerate(story):            # weave the narrative between the topic sentences
            sentences.insert(1 + 2 * i, s)
    closer = rng.choice(CLOSERS[rating])
    if closer:
        sentences.append(closer)
    return rng.choice(TITLES[rating]), ' '.join(sentences), topics, site


def build_reviews(tables, kinds):
    rng = random.Random(SEED + 1)
    products = {p['product_id']: p for p in tables['products']}
    customers = [a['account_id'] for a in tables['accounts'] if a['account_type'] == 'user']
    orders = {o['order_id']: o for o in tables['orders']}

    # verified purchases: delivered orders of registered customers, one candidate per (account, product)
    verified = {}
    for item in tables['order_items']:
        o = orders[item['order_id']]
        if o['account_id'] and o['delivered_at']:
            verified.setdefault((o['account_id'], item['product_id']), o)
    pairs = [(acct, pid, o) for (acct, pid), o in verified.items() if rng.random() < 0.85]
    used = {(a, p) for a, p, _ in pairs}
    product_ids = sorted(products)
    while len(pairs) < N_REVIEWS:
        acct, pid = rng.choice(customers), rng.choice(product_ids)
        if (acct, pid) not in used:
            used.add((acct, pid))
            pairs.append((acct, pid, None))
    pairs = pairs[:N_REVIEWS]

    long_ids = set(rng.sample(range(N_REVIEWS), N_LONG))
    rest = [i for i in range(N_REVIEWS) if i not in long_ids]
    empty_ids = set(rng.sample(rest, N_EMPTY))
    rest = [i for i in rest if i not in empty_ids]
    short_ids = set(rng.sample(rest, N_VERY_SHORT))

    drafts = []
    for i, (acct, pid, order) in enumerate(pairs):
        product = products[pid]
        ptype = kinds[pid][1]
        rating = rng.choices([5, 4, 3, 2, 1], weights=[36, 28, 16, 11, 9])[0]
        title, body, topics, site = build_review_text(rng, product, ptype, rating, long_form=i in long_ids)
        if i in empty_ids:
            body, topics = rng.choice(['', '   ', '\t']), []
        elif i in short_ids:
            body, topics = rng.choice(SHORT_BODIES), []
        if order is not None:
            created = order['delivered_at'] + timedelta(days=rng.randint(2, 45), minutes=rng.randint(0, 1439))
        else:
            created = FIRST_REVIEW + timedelta(minutes=rng.randint(0, int((LAST_REVIEW - FIRST_REVIEW).total_seconds() // 60)))
        created = min(created, LAST_REVIEW)

        sub = {'quality': max(1, min(5, rating + rng.choice([-1, 0, 0, 1]))),
               'value': max(1, min(5, rating + rng.choice([-1, 0, 0, 1])))}
        if kinds[pid][0] == 'WEARABLE':
            sub['fit'] = max(1, min(5, rating + rng.choice([-2, -1, 0, 0, 1])))
        details = {'ratings': sub}
        topic_names = {t for t, _ in topics}
        if topic_names & (COLD_TOPICS | {'battery'}) or rng.random() < 0.5:
            details['dive_context'] = {'site': site[0], 'region': site[1], 'water_temp_c': site[2],
                                       'depth_m': rng.choice([8, 12, 15, 18, 22, 25, 30, 35])}
        if rng.random() < 0.2:
            details['photos'] = [{'caption': rng.choice(['On the boat', 'After the dive', 'Close-up', 'Out of the box'])}
                                 for _ in range(rng.randint(1, 2))]
        drafts.append({'created_at': created, 'product_id': pid, 'account_id': acct,
                       'order_id': order['order_id'] if order else None, 'rating': rating, 'title': title,
                       'body': body, 'details': details, 'helpful_votes': rng.choices(
                           [0, 1, 2, 3, 5, 8, 13], weights=[30, 20, 15, 12, 10, 8, 5])[0], 'topics': topics})

    # review ids follow submission time, like an identity column would
    drafts.sort(key=lambda d: (d['created_at'], d['account_id'], d['product_id']))
    for n, d in enumerate(drafts, 1):
        d['review_id'] = n

    # --- inject the messy-export problems that clean_reviews.py must handle -------------------
    for d in rng.sample(drafts, 60):                        # stray whitespace / line breaks
        if d['body'].strip() and len(d['body']) > 20:
            d['body'] = '  ' + d['body'].replace('. ', '.  \n', 1) + ' '
    for d in rng.sample(drafts, 25):                        # HTML entities from the old web form
        d['body'] = d['body'].replace(' and ', ' &amp; ', 1).replace("'", '&#39;', 1)

    candidates = [d for d in drafts if len(d['body'].strip()) > 40]
    dupes = []
    for d in rng.sample(candidates, N_EXACT_DUPLICATES):       # double submit: identical copy
        dupes.append(dict(d, created_at=d['created_at'] + timedelta(seconds=rng.randint(1, 20)), topics=[]))
    for d in rng.sample(candidates, N_NEAR_DUPLICATES):        # re-submitted later, retyped spacing/case
        body = d['body'].strip()
        body = body[0].lower() + body[1:].replace('. ', '.   ') if rng.random() < 0.5 else body.upper()
        dupes.append(dict(d, body=body, created_at=d['created_at'] + timedelta(hours=rng.randint(1, 72)), topics=[]))
    dupes.sort(key=lambda d: (d['created_at'], d['review_id']))
    for n, d in enumerate(dupes, len(drafts) + 1):
        d['review_id'] = n
    return drafts + dupes


