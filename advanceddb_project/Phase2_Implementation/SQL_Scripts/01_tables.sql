-- Aria Phase 2: tables, keys and constraints.
-- Run while connected to aria_phase2.
--
-- The first 10 tables match the Django app's live schema (exported with pg_dump, see
-- reference/app_schema_export.sql) column-for-column. Differences are deliberate and listed
-- in schema_reconciliation.md:
--   * readable constraint names instead of Django's hashed ones
--   * ON DELETE behaviour declared in the database (Django only enforces it in Python)
--   * extra CHECK constraints for rules the app enforces only in code
--   * orders.shipped_at / delivered_at (needed for carrier performance reporting)
--   * 6 tables designed in Phase 1 but not yet in the app: suppliers, refunds,
--     duplicate_refund_attempts, accounts_receivable, accounts_payable, policy_documents
--
-- All data in this database is synthetic.

BEGIN;

-- ---------------------------------------------------------------------------
-- Accounts (supertype for customers, staff and admins; overlapping roles are
-- modelled with a single account_type column, as in the app)
-- ---------------------------------------------------------------------------
CREATE TABLE accounts (
    account_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(100) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    account_type    VARCHAR(50)  NOT NULL DEFAULT 'user',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT accounts_username_unique UNIQUE (username),
    CONSTRAINT accounts_type_valid CHECK (account_type IN ('user', 'staff', 'admin'))
);

CREATE TABLE profiles (
    profile_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT       NOT NULL,
    first_name      VARCHAR(100),
    last_name       VARCHAR(100),
    phone           VARCHAR(20),
    email           VARCHAR(254) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT profiles_account_unique UNIQUE (account_id),
    CONSTRAINT profiles_email_unique UNIQUE (email),
    CONSTRAINT profiles_email_format CHECK (email LIKE '%_@_%'),
    CONSTRAINT profiles_account_fk FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE CASCADE
);

CREATE TABLE addresses (
    address_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT       NOT NULL,
    address_type    VARCHAR(10)  NOT NULL,
    line1           VARCHAR(255) NOT NULL,
    line2           VARCHAR(255),
    city            VARCHAR(100) NOT NULL,
    region          VARCHAR(100) NOT NULL,
    postal_code     VARCHAR(20)  NOT NULL,
    country         VARCHAR(2)   NOT NULL,
    is_default      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT addresses_type_valid CHECK (address_type IN ('SHIPPING', 'BILLING')),
    CONSTRAINT addresses_country_valid CHECK (country IN ('CA', 'US')),
    CONSTRAINT addresses_account_fk FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Catalogue
-- ---------------------------------------------------------------------------
CREATE TABLE categories (
    category_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    description     TEXT,
    CONSTRAINT categories_name_unique UNIQUE (name)
);

CREATE TABLE products (
    product_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(50)   NOT NULL,
    name            VARCHAR(255)  NOT NULL,
    description     TEXT,
    category_id     BIGINT,
    unit_price      NUMERIC(10,2) NOT NULL,
    currency        VARCHAR(3)    NOT NULL DEFAULT 'CAD',
    stock_quantity  INTEGER       NOT NULL DEFAULT 0,
    reorder_level   INTEGER       NOT NULL DEFAULT 10,
    is_active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT products_sku_unique UNIQUE (sku),
    CONSTRAINT products_stock_nonnegative CHECK (stock_quantity >= 0),
    CONSTRAINT products_price_nonnegative CHECK (unit_price >= 0),
    CONSTRAINT products_reorder_nonnegative CHECK (reorder_level >= 0),
    CONSTRAINT products_currency_valid CHECK (currency IN ('CAD', 'USD')),
    CONSTRAINT products_category_fk FOREIGN KEY (category_id)
        REFERENCES categories (category_id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------------
-- Payees: disjoint subtypes Supplier | Carrier (Phase 1 EERD).
-- Implemented as an exclusive arc on accounts_payable: each bill points at exactly
-- one supplier OR one carrier (see accounts_payable_one_payee below).
-- ---------------------------------------------------------------------------
CREATE TABLE carriers (
    carrier_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(100) NOT NULL,
    tracking_url_template   VARCHAR(500),
    CONSTRAINT carriers_name_unique UNIQUE (name),
    CONSTRAINT carriers_tracking_template CHECK (
        tracking_url_template IS NULL OR tracking_url_template LIKE '%{tracking_number}%')
);

CREATE TABLE suppliers (
    supplier_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL,
    contact_email       VARCHAR(254) NOT NULL,
    phone               VARCHAR(20),
    country             VARCHAR(2)   NOT NULL,
    payment_terms_days  INTEGER      NOT NULL DEFAULT 30,
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT suppliers_name_unique UNIQUE (name),
    CONSTRAINT suppliers_country_valid CHECK (country IN ('CA', 'US')),
    CONSTRAINT suppliers_terms_valid CHECK (payment_terms_days IN (15, 30, 45, 60))
);

-- ---------------------------------------------------------------------------
-- Orders and payments.
-- orders.confirmed_payment_id -> payments and payments.order_id -> orders form a cycle,
-- so the confirmed_payment FK is DEFERRABLE and added after payments exists.
-- Addresses are snapshotted onto the order so later address edits never rewrite history.
-- ---------------------------------------------------------------------------
CREATE TABLE orders (
    order_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id              BIGINT,                     -- NULL for guest checkout
    status                  VARCHAR(20)   NOT NULL DEFAULT 'PENDING_PAYMENT',
    contact_name            VARCHAR(200)  NOT NULL,
    contact_email           VARCHAR(254),
    ship_line1              VARCHAR(255)  NOT NULL,
    ship_line2              VARCHAR(255),
    ship_city               VARCHAR(100)  NOT NULL,
    ship_region             VARCHAR(100)  NOT NULL,
    ship_postal_code        VARCHAR(20)   NOT NULL,
    ship_country            VARCHAR(2)    NOT NULL,
    bill_line1              VARCHAR(255)  NOT NULL,
    bill_line2              VARCHAR(255),
    bill_city               VARCHAR(100)  NOT NULL,
    bill_region             VARCHAR(100)  NOT NULL,
    bill_postal_code        VARCHAR(20)   NOT NULL,
    bill_country            VARCHAR(2)    NOT NULL,
    shipping_method         VARCHAR(10)   NOT NULL,
    subtotal                NUMERIC(10,2) NOT NULL,
    shipping_cost           NUMERIC(10,2) NOT NULL,
    tax_amount              NUMERIC(10,2) NOT NULL,
    total_amount            NUMERIC(10,2) NOT NULL,
    checkout_token          UUID          NOT NULL,
    confirmed_payment_id    BIGINT,
    risk_score              NUMERIC(5,2),               -- staff/admin only, never customer-facing
    carrier_id              BIGINT,
    tracking_number         VARCHAR(100),
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    confirmed_at            TIMESTAMPTZ,
    shipped_at              TIMESTAMPTZ,
    delivered_at            TIMESTAMPTZ,
    -- one order per checkout attempt: a double submit reuses the same token
    CONSTRAINT orders_checkout_token_unique UNIQUE (checkout_token),
    CONSTRAINT orders_confirmed_payment_unique UNIQUE (confirmed_payment_id),
    CONSTRAINT orders_status_valid CHECK (status IN (
        'PENDING_PAYMENT', 'PAYMENT_FAILED', 'OUT_OF_STOCK', 'CONFIRMED',
        'SHIPPED', 'DELIVERED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT orders_shipping_method_valid CHECK (shipping_method IN ('STANDARD', 'EXPRESS', 'PRIORITY')),
    CONSTRAINT orders_ship_country_valid CHECK (ship_country IN ('CA', 'US')),
    CONSTRAINT orders_bill_country_valid CHECK (bill_country IN ('CA', 'US')),
    -- business invariant 1: an order is never "confirmed" without a successful payment
    CONSTRAINT orders_confirmed_requires_payment CHECK (
        status NOT IN ('CONFIRMED', 'SHIPPED', 'DELIVERED', 'REFUNDED')
        OR (confirmed_payment_id IS NOT NULL AND confirmed_at IS NOT NULL)),
    -- guests have no account, so they must leave an email
    CONSTRAINT orders_has_owner CHECK (
        account_id IS NOT NULL OR (contact_email IS NOT NULL AND contact_email <> '')),
    CONSTRAINT orders_money_nonnegative CHECK (
        subtotal >= 0 AND shipping_cost >= 0 AND tax_amount >= 0 AND total_amount >= 0),
    CONSTRAINT orders_total_adds_up CHECK (total_amount = subtotal + shipping_cost + tax_amount),
    CONSTRAINT orders_risk_score_range CHECK (risk_score IS NULL OR risk_score BETWEEN 0 AND 100),
    CONSTRAINT orders_shipped_has_tracking CHECK (
        status NOT IN ('SHIPPED', 'DELIVERED')
        OR (carrier_id IS NOT NULL AND tracking_number IS NOT NULL AND shipped_at IS NOT NULL)),
    CONSTRAINT orders_delivered_has_date CHECK (status <> 'DELIVERED' OR delivered_at IS NOT NULL),
    CONSTRAINT orders_timeline_ordered CHECK (
        (confirmed_at IS NULL OR confirmed_at >= created_at)
        AND (shipped_at IS NULL OR shipped_at >= confirmed_at)
        AND (delivered_at IS NULL OR delivered_at >= shipped_at)),
    CONSTRAINT orders_account_fk FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE RESTRICT,
    CONSTRAINT orders_carrier_fk FOREIGN KEY (carrier_id)
        REFERENCES carriers (carrier_id) ON DELETE SET NULL
);

-- Only a token from the payment provider and the last 4 digits are stored.
-- There is no column that could hold a full card number.
CREATE TABLE payments (
    payment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    amount          NUMERIC(10,2) NOT NULL,
    method_type     VARCHAR(20)   NOT NULL,
    token           VARCHAR(255)  NOT NULL,
    last4           VARCHAR(4),
    card_brand      VARCHAR(20)   NOT NULL DEFAULT '',
    status          VARCHAR(20)   NOT NULL,
    gateway_ref     VARCHAR(255),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT payments_amount_nonnegative CHECK (amount >= 0),
    CONSTRAINT payments_method_valid CHECK (method_type IN ('CREDIT_CARD', 'DEBIT_CARD', 'PAYPAL', 'GIFT_CARD')),
    CONSTRAINT payments_status_valid CHECK (status IN ('AUTHORIZED', 'CAPTURED', 'DECLINED', 'VOIDED', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_last4_digits CHECK (last4 IS NULL OR last4 ~ '^[0-9]{4}$'),
    -- cards carry last4 + brand; wallets and gift cards do not (disjoint payment types)
    CONSTRAINT payments_card_fields CHECK (
        (method_type IN ('CREDIT_CARD', 'DEBIT_CARD') AND last4 IS NOT NULL AND card_brand <> '')
        OR (method_type IN ('PAYPAL', 'GIFT_CARD') AND last4 IS NULL)),
    CONSTRAINT payments_order_fk FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT
);

ALTER TABLE orders
    ADD CONSTRAINT orders_confirmed_payment_fk FOREIGN KEY (confirmed_payment_id)
        REFERENCES payments (payment_id) ON DELETE RESTRICT
        DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE order_items (
    order_item_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    product_id      BIGINT        NOT NULL,
    quantity        INTEGER       NOT NULL,
    unit_price      NUMERIC(10,2) NOT NULL,         -- price snapshot at checkout
    line_total      NUMERIC(10,2) NOT NULL,
    CONSTRAINT order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT order_items_money_nonnegative CHECK (unit_price >= 0 AND line_total >= 0),
    CONSTRAINT order_items_line_total CHECK (line_total = quantity * unit_price),
    CONSTRAINT order_items_one_line_per_product UNIQUE (order_id, product_id),
    CONSTRAINT order_items_order_fk FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE CASCADE,
    CONSTRAINT order_items_product_fk FOREIGN KEY (product_id)
        REFERENCES products (product_id) ON DELETE RESTRICT
);

-- Every stock change is logged here in the same transaction that changes products.stock_quantity.
CREATE TABLE inventory_movements (
    movement_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT      NOT NULL,
    change_qty          INTEGER     NOT NULL,
    reason              VARCHAR(20) NOT NULL,
    reference_order_id  BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT inv_mov_reason_valid CHECK (reason IN ('SALE', 'RESTOCK', 'REFUND', 'ADJUSTMENT')),
    CONSTRAINT inv_mov_sign_matches_reason CHECK (
        (reason = 'SALE' AND change_qty < 0)
        OR (reason IN ('RESTOCK', 'REFUND') AND change_qty > 0)
        OR (reason = 'ADJUSTMENT' AND change_qty <> 0)),
    CONSTRAINT inv_mov_sale_has_order CHECK (reason NOT IN ('SALE', 'REFUND') OR reference_order_id IS NOT NULL),
    CONSTRAINT inv_mov_product_fk FOREIGN KEY (product_id)
        REFERENCES products (product_id) ON DELETE RESTRICT,
    CONSTRAINT inv_mov_order_fk FOREIGN KEY (reference_order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------------
-- Refunds (business invariant 3: idempotent, duplicates rejected and flagged)
-- ---------------------------------------------------------------------------
CREATE TABLE refunds (
    refund_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    payment_id      BIGINT        NOT NULL,
    amount          NUMERIC(10,2) NOT NULL,
    reason          VARCHAR(255)  NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'REQUESTED',
    idempotency_key UUID          NOT NULL,
    requested_by    BIGINT,                         -- NULL when a guest requests via order link
    resolved_by     BIGINT,
    risk_score      NUMERIC(5,2),                   -- staff/admin only
    requested_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMPTZ,
    CONSTRAINT refunds_idempotency_key_unique UNIQUE (idempotency_key),
    CONSTRAINT refunds_amount_positive CHECK (amount > 0),
    CONSTRAINT refunds_status_valid CHECK (status IN ('REQUESTED', 'APPROVED', 'DENIED', 'COMPLETED')),
    CONSTRAINT refunds_resolution_consistent CHECK (
        (status = 'REQUESTED' AND resolved_at IS NULL AND resolved_by IS NULL)
        OR (status <> 'REQUESTED' AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL)),
    CONSTRAINT refunds_resolved_after_request CHECK (resolved_at IS NULL OR resolved_at >= requested_at),
    CONSTRAINT refunds_risk_score_range CHECK (risk_score IS NULL OR risk_score BETWEEN 0 AND 100),
    CONSTRAINT refunds_order_fk FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT,
    CONSTRAINT refunds_payment_fk FOREIGN KEY (payment_id)
        REFERENCES payments (payment_id) ON DELETE RESTRICT,
    CONSTRAINT refunds_requested_by_fk FOREIGN KEY (requested_by)
        REFERENCES accounts (account_id) ON DELETE SET NULL,
    CONSTRAINT refunds_resolved_by_fk FOREIGN KEY (resolved_by)
        REFERENCES accounts (account_id) ON DELETE SET NULL
);

-- Admin review queue for blocked duplicate refund attempts.
CREATE TABLE duplicate_refund_attempts (
    attempt_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT      NOT NULL,
    idempotency_key     UUID        NOT NULL,
    existing_refund_id  BIGINT,
    attempt_reason      VARCHAR(30) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_by         BIGINT,
    reviewed_at         TIMESTAMPTZ,
    CONSTRAINT dup_refund_reason_valid CHECK (
        attempt_reason IN ('SAME_KEY', 'OPEN_REFUND_EXISTS', 'EXCEEDS_ORDER_TOTAL')),
    CONSTRAINT dup_refund_review_consistent CHECK ((reviewed_by IS NULL) = (reviewed_at IS NULL)),
    CONSTRAINT dup_refund_order_fk FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE CASCADE,
    CONSTRAINT dup_refund_existing_fk FOREIGN KEY (existing_refund_id)
        REFERENCES refunds (refund_id) ON DELETE SET NULL,
    CONSTRAINT dup_refund_reviewer_fk FOREIGN KEY (reviewed_by)
        REFERENCES accounts (account_id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------------
-- Receivables / payables (status tracking only; full accounting is out of scope)
-- ---------------------------------------------------------------------------
-- Money owed TO Aria: captured card payments awaiting settlement from the processor.
CREATE TABLE accounts_receivable (
    ar_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    payment_id      BIGINT        NOT NULL,
    amount_due      NUMERIC(10,2) NOT NULL,
    due_date        DATE          NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    settled_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ar_payment_unique UNIQUE (payment_id),
    CONSTRAINT ar_amount_nonnegative CHECK (amount_due >= 0),
    CONSTRAINT ar_status_valid CHECK (status IN ('OPEN', 'PAID', 'OVERDUE', 'WRITTEN_OFF')),
    CONSTRAINT ar_paid_has_date CHECK ((status = 'PAID') = (settled_at IS NOT NULL)),
    CONSTRAINT ar_order_fk FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT,
    CONSTRAINT ar_payment_fk FOREIGN KEY (payment_id)
        REFERENCES payments (payment_id) ON DELETE RESTRICT
);

-- Money Aria owes a payee. Exactly one of supplier_id / carrier_id is set (disjoint Payee subtype).
CREATE TABLE accounts_payable (
    ap_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id     BIGINT,
    carrier_id      BIGINT,
    invoice_number  VARCHAR(40)   NOT NULL,
    description     VARCHAR(255)  NOT NULL,
    amount_due      NUMERIC(10,2) NOT NULL,
    invoice_date    DATE          NOT NULL,
    due_date        DATE          NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    paid_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ap_one_payee CHECK (num_nonnulls(supplier_id, carrier_id) = 1),
    CONSTRAINT ap_amount_positive CHECK (amount_due > 0),
    CONSTRAINT ap_due_after_invoice CHECK (due_date >= invoice_date),
    CONSTRAINT ap_status_valid CHECK (status IN ('OPEN', 'PAID', 'OVERDUE')),
    CONSTRAINT ap_paid_has_date CHECK ((status = 'PAID') = (paid_at IS NOT NULL)),
    CONSTRAINT ap_supplier_fk FOREIGN KEY (supplier_id)
        REFERENCES suppliers (supplier_id) ON DELETE RESTRICT,
    CONSTRAINT ap_carrier_fk FOREIGN KEY (carrier_id)
        REFERENCES carriers (carrier_id) ON DELETE RESTRICT
);
-- the same payee can't send the same invoice number twice
CREATE UNIQUE INDEX ap_invoice_unique_per_payee
    ON accounts_payable (COALESCE(supplier_id, 0), COALESCE(carrier_id, 0), invoice_number);

-- ---------------------------------------------------------------------------
-- Policy documents: metadata for the ~20 documents behind the RAG chatbot.
-- The document text itself lives in files / the retrieval index, not here.
-- ---------------------------------------------------------------------------
CREATE TABLE policy_documents (
    document_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(255) NOT NULL,
    category        VARCHAR(100) NOT NULL,
    file_path       VARCHAR(500) NOT NULL,
    version         VARCHAR(20)  NOT NULL DEFAULT '1.0',
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    last_updated    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT policy_documents_path_version_unique UNIQUE (file_path, version),
    CONSTRAINT policy_documents_category_valid CHECK (category IN (
        'Shipping', 'Returns & Refunds', 'Payments', 'Orders', 'Products & Safety',
        'Privacy', 'Account', 'Warranty'))
);

COMMIT;
